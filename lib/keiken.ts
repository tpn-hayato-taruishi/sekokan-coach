export function getExamReference(examId: ExamId): string {
  if (examId === 'denki_1' || examId === 'denki_2') {
    const shikaku = examId === 'denki_2' ? DENKI2_SHIKAKU_REF : DENKI1_SHIKAKU_REF;
    return `${CTABLE_LAYOUT_REF}\n\n${DENKI_SCOPE_REF}\n\n${shikaku}`;
  }
  // 電気通信工事（tsushin_1 / tsushin_2）
  const shikaku = examId === 'tsushin_2'
    ? TSUSHIN2_SHIKAKU_REF
    : `【受検資格：1級・電気通信工事】本ツールが保有する手引は2級用のため、1級の実務経験年数要件は断定しない。工事種別・立場・認められないもの（表Ⅰ〜表Ⅳ）は1級も同様に適用してよいが、必要年数は1級の公式手引で確認するよう促すこと。`;
  return `${TSUSHIN_LAYOUT_REF}\n\n${TSUSHIN_SCOPE_REF}\n\n${shikaku}`;
}
