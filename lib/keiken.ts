// 試験区分ごとに、プロンプトに注入する参照テキストを返す
export function getExamReference(examId: ExamId): string {
  const isDenki = examId === 'denki_1' || examId === 'denki_2';
  if (!isDenki) {
    // 電気通信工事：本ツールは電気通信の公式手引を未保有
    return `${CTABLE_LAYOUT_REF}

【注意：電気通信工事施工管理の受検の手引は本ツールに読み込まれていません】
電気通信工事は電気工事とは工事種別・認定範囲が異なります（電気通信線路・放送・データ通信等は電気通信側で認められる一方、これらは電気工事側では認められない）。工事種別・認定可否・受験資格年数は断定せず、必ず電気通信工事施工管理の公式「受検の手引」で確認するよう促すこと。一般的な様式ルール（上記C票の構造）のみ適用する。`;
  }
  const shikaku = examId === 'denki_2'
    ? DENKI2_SHIKAKU_REF
    : `【受検資格：1級・電気工事】本ツールが保有する手引は2級用のため、1級の実務経験年数要件は断定しない。工事種別・立場・認められないものの範囲（表Ⅰ・表Ⅱ・除外）は1級も同様に適用してよいが、必要年数・指導監督的実務経験の要否は1級の公式手引で確認するよう促すこと。`;
  return `${CTABLE_LAYOUT_REF}\n\n${DENKI_SCOPE_REF}\n\n${shikaku}`;
}
